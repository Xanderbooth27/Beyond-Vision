export const CONTACT_EMAIL = "campaigns@beyondvisionltd.org";

const LEGACY_CONTACT_EMAILS = new Set([
  "info@beyondvision.com",
  "hq@beyondvision.com",
  "campagins@beyondvisionltd.org",
]);

export function resolveContactEmail(email?: string | null): string {
  if (!email) return CONTACT_EMAIL;
  const normalized = email.trim().toLowerCase();
  if (LEGACY_CONTACT_EMAILS.has(normalized)) return CONTACT_EMAIL;
  return email.trim();
}

export function getPageDefinition(pageId: string) {
  return PAGE_DEFINITIONS.find((page) => page.id === pageId);
}
